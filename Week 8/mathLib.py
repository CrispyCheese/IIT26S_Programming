def add(Pvalue1:float, Pvalue2:float)->float:
    return (Pvalue1 + Pvalue2)

def subtract(Pvalue:float, PsubtractThis:float)->float:
    return (Pvalue - PsubtractThis)

def multiply(Pvalue:float, Pmultiplier:float)->float:
    return (Pvalue * Pmultiplier)

def divide(Pvalue:float, Pdivisor:float)->float:
    return (Pvalue / Pdivisor)